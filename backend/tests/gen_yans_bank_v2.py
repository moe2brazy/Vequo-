def build_bank_v2() -> list[dict]:
    bank = []
    seen = set()

    def add(q, expect):
        q = q.strip()
        if not q or q in seen:
            return
        seen.add(q)
        bank.append({"q": q, "expect": expect})

    # 1) 倒装 Top 问法
    for q, exp in INVERTED:
        add(q, exp)

    # 2) 英文列名提示
    for q, exp in COL_HINT:
        add(q, exp)

    # 3) 口语化前缀 × 指标×维度主问法（每指标取前 2 个维度控制量）
    for metric, dims in COMMON_DIMS.items():
        for d in dims[:2]:
            for p in random.sample(SPOKEN_PREFIX, 2):
                add(f"{p}各{d}的{metric}", "group")
        add(f"{random.choice(SPOKEN_PREFIX)}总的{metric}", "total")
        add(f"{random.choice(SPOKEN_PREFIX)}{metric}是多少", "total")

    # 4) 时间窗口变体 × 有时间列指标
    time_metrics = ["产量", "良率", "停机时长", "停机次数", "库存量", "工单数", "抽检数", "检验次数"]
    for tm in time_metrics:
        d0 = COMMON_DIMS[tm][0]
        for tv in TIME_VARIANTS[:6]:
            add(f"{tv}各{d0}的{tm}", "group")
        add(f"{TIME_VARIANTS[0]}{tm}", "total")

    # 5) 区间/否定/比较
    for q, exp in FILTER_VARIANTS:
        add(q, exp)

    # 6) 钻取
    for q, exp in DRILL:
        add(q, exp)

    # 7) 同义指标词 × 首个维度
    for std, syns in SYNONYM_METRICS.items():
        dims = COMMON_DIMS.get(std, [])
        for syn in syns[:2]:
            if dims:
                add(f"各{dims[0]}的{syn}", "group")
            add(syn, "total")

    # 8) 模糊/歧义
    for q, exp in AMBIGUOUS:
        add(q, exp)

    # 9) 冗余修饰问法（验证编译器抗干扰）
    add("给我统计一下各工序的良率情况怎么样", "group")
    add("麻烦看看我们各产线的产量数据", "group")
    add("帮我查查所有设备的停机情况", "group")
    add("请问一下各产品的库存现在怎么样", "group")
    add("我想知道每个工序的返工情况", "group")
    add("汇总一下各车间设备的状态分布", "group")
    add("看看不同班次的产量对比", "group")
    add("各产线的良率怎么样，排个名", "rank")
    add("停机原因按次数排一下", "llm")
    add("缺陷类型按件数排名", "llm")

    return bank

