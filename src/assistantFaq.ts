/**
 * 相似问题匹配 —— 判定"是否与预设问答足够相似"
 *
 * 用**字符 bigram 相似度**而不是"命中任意关键词"，避免长问题里蹭到一个主题词就被预设吞掉：
 *  - 用户输入与预设问句的 bigram Jaccard 相似度 ≥ 0.5 → 命中（复用预设答案）
 *  - 输入 ≥4 字且与预设问句互为包含（去标点）→ 视为完全命中（如"忘记密码" ⊂ "忘记密码怎么办？"）
 *  - 关键词兜底：命中 ≥2 个关键词（≥2 字）且相似度 ≥0.3 → 命中（应对同义改写）
 *  - 其余一律返回 null，由调用方转交接入的 AI 接口回答
 *
 * 反例（都会被判为不相似 → 走 AI）：
 *  - "如何修改密码" vs "忘记密码怎么办？"（只蹭到"密码"）
 *  - "我的账号被禁用了，登录不上怎么办" vs "忘记密码怎么办？"（只蹭到"账号/登录不上"，且需转人工）
 *  - "数据表可以分享给别人吗" vs "怎么搜索数据表？"
 */
export function matchFaq(q: string): FaqItem | null {
  const s = (q || '').toLowerCase().trim()
  if (!s) return null
  const strip = (t: string) => t.replace(/[？?。.！!，,、;；:：\s"'“”‘’（）()【】\-_/]/g, '')
  const sq = strip(s)
  if (!sq) return null

  const bigrams = (t: string): Set<string> => {
    const set = new Set<string>()
    for (let i = 0; i + 1 < t.length; i++) set.add(t.slice(i, i + 2))
    return set
  }
  const a = bigrams(sq)

  let best: FaqItem | null = null
  let bestSim = 0
  for (const group of Object.values(FAQS)) {
    for (const f of group) {
      const fq = strip(f.q.toLowerCase())
      if (!fq) continue
      const b = bigrams(fq)
      let inter = 0
      for (const g of a) if (b.has(g)) inter += 1
      const union = a.size + b.size - inter
      let sim = union > 0 ? inter / union : 0
      // 单字输入没有 bigram，退化为字符包含
      if (a.size === 0) sim = fq.includes(sq) ? 1 : 0
      // 互为包含（输入较短需 ≥4 字，否则"搜索"这类短词会被预设问句包含而误命中）
      if (sq.length >= 4 && (fq.includes(sq) || sq.includes(fq))) sim = 1
      // 关键词兜底：≥2 个有效关键词命中 + 相似度不低
      const kw = f.keywords.filter((k) => {
        const kk = k.toLowerCase().trim()
        return kk.length >= 2 && s.includes(kk)
      }).length
      if (kw >= 2 && sim >= 0.3) sim = Math.max(sim, 0.5)
      if (sim > bestSim) {
        bestSim = sim
        best = f
      }
    }
  }
  return bestSim >= 0.5 ? best : null
}
